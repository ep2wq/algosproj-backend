## كيف تفكر في الحل
اجعل العدد الأول قيمة `best` الابتدائية، ثم قارن به كل عدد آخر مرة واحدة. لا تستبدل `best` إلا عندما يكون العدد أكبر منها. عند تساوي القيم لا يهم أيها تحتفظ به، لأنك تطبع القيمة لا موضعها. كما في المجموع، هذا مرور واحد (single pass) على البيانات، لذا يمكنك أن تقارن كل عدد فور قراءته دون أن تخزن المصفوفة (Array) أبدًا. ترتيب (sorting) المصفوفة وأخذ آخر عنصر فيها يعطي الإجابة الصحيحة أيضًا، لكنه يؤدي عملًا أكثر بكثير مما يلزم.

