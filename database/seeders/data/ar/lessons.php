المصفوفة (Array) قائمة من القيم المخزنة واحدة تلو الأخرى، ولكل قيمة موضع مرقّم يبدأ من `0`. لجمع هذه القيم، احتفظ بمجموع تراكمي (running total)، كما تجمع آلة الدفع في المتجر سعر كل سلعة لحظة مسحها.

## مثال
المدخلات هي `n = 5` والأعداد `10 -2 7 0 5`.
ابدأ بالقيمة `total = 0`.
أضف `10`: `total = 10`.
أضف `-2`: `total = 8`.
أضف `7`: `total = 15`.
أضف `0`: `total = 15`.
أضف `5`: `total = 20`.
اطبع `20`.

## كيف تفكر في الحل
اقرأ `n` أولًا، ثم اقرأ `n` عددًا بالضبط. ابدأ المجموع من `0` لا من العدد الأول، حتى يعمل الحل مع المصفوفة الفارغة أيضًا. أضف كل عدد مرة واحدة. لا تحتاج إلى الأعداد بعد إضافتها، لذا يمكنك أن تضيف كل عدد فور قراءته بدلًا من تخزين المصفوفة كلها. يتكرر هذا النمط في كثير من المسائل اللاحقة: متغير واحد يتغير خلال مرور واحد (single pass) على البيانات.

## التعقيد
الوقت: `O(n)`، لأن كل عدد يُقرأ ويُضاف مرة واحدة.
الذاكرة: `O(1)` إضافية إذا أضفت كل عدد فور قراءته، و`O(n)` إذا خزّنت الأعداد كلها أولًا. كلا الحلين مقبول بهذا الحجم.

## انتبه إلى
